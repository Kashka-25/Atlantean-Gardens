"""Lift each realm's parchment shield (with its painted words) off the painting.

For every realm painting this writes:
  assets/realms/<id>-shield.png  the parchment shield and its vine frame, cut
                                 out with a soft edge (transparent around it)
  assets/realms/<id>-base.jpg    the painting with the shield's area softly
                                 filled from the surrounding scenery
The realm scene shows the base painting and floats the shield above it in the
same spot. The original paintings are not changed.

BOXES: the shield's bounds in pixels of the 1536x1024 painting.
Usage: python tools/lift_shields.py   (run from living-atlas/)
"""
import json

import numpy as np
from PIL import Image, ImageFilter

BOXES = {
    "sunlight-realms": (0, 0, 368, 402),
    "bubble-coast-realm": (8, 8, 382, 418),
    "living-harvest-realm": (0, 0, 402, 388),
    "crystal-conservatory-realm": (0, 0, 418, 442),
    "hearthlands-realm": (0, 0, 402, 418),
    "verdant-wilds-realm": (0, 0, 448, 458),
    "celestial-realm": (0, 0, 362, 332),
    "heart-of-atlantis": (0, 0, 372, 326),
}


def _box1d(a, r, axis):
    a = np.moveaxis(a, axis, 0)
    p = np.pad(a, [(r, r)] + [(0, 0)] * (a.ndim - 1), mode="edge")
    c = np.cumsum(p, axis=0, dtype=np.float64)
    c = np.concatenate([np.zeros((1,) + c.shape[1:]), c])
    return np.moveaxis(((c[2 * r + 1:] - c[:-2 * r - 1]) / (2 * r + 1)).astype(np.float32), 0, axis)


def blur(a, r):
    a = a.astype(np.float32)
    k = max(1, int(round(r * 0.9)))
    for _ in range(3):
        a = _box1d(_box1d(a, k, 0), k, 1)
    return a


def morph(mask, size, times, grow=True):
    im = Image.fromarray((mask * 255).astype(np.uint8))
    f = ImageFilter.MaxFilter(size) if grow else ImageFilter.MinFilter(size)
    for _ in range(times):
        im = im.filter(f)
    return np.asarray(im) > 127


meta = {}
for rid, (l, t, r, b) in BOXES.items():
    img = Image.open(f"assets/realms/{rid}.jpg").convert("RGB")
    im = np.asarray(img).astype(np.float32)
    H, W = im.shape[:2]
    lum = im @ np.array([.299, .587, .114], np.float32)
    sat = im.max(-1) - im.min(-1)
    inbox = np.zeros((H, W), bool)
    inbox[t:b, l:r] = True
    # the parchment: bright, softly coloured paper inside the box
    # work in the corner only (fast), then place back
    C = 520
    sub = ((lum > 150) & (sat < 95) & inbox)[:C, :C]
    sub = morph(sub, 15, 3, True)            # close over the lettering
    sub = morph(sub, 15, 3, False)
    sub = morph(sub, 15, 2, False)           # drop stray bright specks
    sub = morph(sub, 15, 2, True)
    # make the shield solid: fill each row and column between its paper edges
    rows = np.zeros_like(sub); cols = np.zeros_like(sub)
    for y in range(C):
        xs_ = np.where(sub[y])[0]
        if xs_.size: rows[y, xs_.min():xs_.max() + 1] = True
    for x in range(C):
        ys_ = np.where(sub[:, x])[0]
        if ys_.size: cols[ys_.min():ys_.max() + 1, x] = True
    sub = rows & cols
    sub = morph(sub, 9, 3, True)             # take in the vine frame
    shield = np.zeros((H, W), bool)
    shield[:C, :C] = sub
    shield &= inbox
    alpha = np.clip(blur(shield.astype(np.float32), 2.5) * 1.25 - .12, 0, 1)

    # 1) the shield layer, cropped to its own bounds
    ys, xs = np.where(alpha > .02)
    y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    rgba = np.dstack([im, alpha * 255])[y0:y1, x0:x1]
    Image.fromarray(np.clip(rgba, 0, 255).astype(np.uint8), "RGBA").save(f"assets/realms/{rid}-shield.png", optimize=True)

    # 2) the base painting: fill under the shield from the scenery around it
    hole = morph(alpha > .01, 9, 2, True)
    valid = (~hole).astype(np.float32)
    out = im.copy()
    done = np.zeros_like(hole)
    for rad in (8, 18, 34, 60, 100, 160):
        w = blur(valid, rad)
        for c in range(3):
            est = blur(im[..., c] * valid, rad) / np.maximum(w, 1e-4)
            take = hole & ~done & (w > .05)
            out[..., c][take] = est[take]
        done |= hole & (w > .05)
    grain = np.random.default_rng(5).normal(0, 3, hole.shape).astype(np.float32)
    for c in range(3):
        out[..., c][hole] += grain[hole]
    edge = blur(hole.astype(np.float32), 6)[..., None]
    base = im * (1 - edge) + out * edge
    Image.fromarray(np.clip(base, 0, 255).astype(np.uint8)).save(f"assets/realms/{rid}-base.jpg", quality=84, optimize=True, progressive=True)
    meta[rid] = {"x": round(x0 / W * 100, 3), "y": round(y0 / H * 100, 3), "w": round((x1 - x0) / W * 100, 3)}
    print(rid, meta[rid])

with open("js/shields.js", "w", encoding="utf-8") as fh:
    fh.write("/* Generated by tools/lift_shields.py: where each realm's parchment shield floats\n"
             "   (percent of the painting). */\nwindow.SHIELDS = " + json.dumps(meta, indent=1) + ";\n")
